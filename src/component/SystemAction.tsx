import React, { useMemo, useCallback } from "react";
import { useNavigate } from "react-router";
import { PiLockKeyThin } from "react-icons/pi";
import { greeter, type GreeterPower } from "../services/WebGreeter";

export type ActionId = "switch_user" | "hibernate" | "restart" | "shutdown";

export interface ActionConfig {
  id: ActionId;
  label: string;
  isExecutable: boolean;
  onTrigger: () => void;
}

export interface SystemActionProps {
  className?: string;
  onActionTriggered?: (action: ActionId) => void;
  // DIP & ISP: Depend on the segregated GreeterPower abstraction, defaulting to the singleton
  powerService?: GreeterPower;
}

const SystemAction = React.memo(function SystemAction({
  className = "",
  onActionTriggered,
  powerService = greeter,
}: SystemActionProps) {
  const navigate = useNavigate();

  // OCP: Declarative action list—no switch statements or if/else chains required
  const actions: ActionConfig[] = useMemo(
    () => [
      {
        id: "switch_user",
        label: "Switch user",
        isExecutable: true,
        onTrigger: () => navigate("/"),
      },
      {
        id: "restart",
        label: "Restart",
        isExecutable: powerService.canRestart(),
        onTrigger: () => powerService.restart(),
      },
      {
        id: "shutdown",
        label: "Shut down",
        isExecutable: powerService.canShutdown(),
        onTrigger: () => powerService.shutdown(),
      },
    ],
    [powerService, navigate],
  );

  const handleTrigger = useCallback(
    (action: ActionConfig) => {
      if (!action.isExecutable) return;
      action.onTrigger();
      onActionTriggered?.(action.id);
    },
    [onActionTriggered],
  );

  return (
    <nav
      aria-label="System Power Controls"
      className={`inline-flex items-center gap-2.5 text-[13px] font-normal tracking-wide text-white/60 select-none ${className}`}
    >
      <button
        type="button"
        onClick={() => handleTrigger(actions[0])}
        aria-label="Lock screen"
        className="flex items-center justify-center p-0.5 -ml-0.5 rounded-sm hover:text-white hover:bg-white/10 outline-none focus-visible:ring-1 focus-visible:ring-white/50 transition-colors cursor-pointer"
      >
        <PiLockKeyThin className="text-[17px]" aria-hidden="true" />
      </button>

      <div className="flex items-center gap-2" role="group">
        {actions.map((action, index) => (
          <React.Fragment key={action.id}>
            <button
              type="button"
              onClick={() => handleTrigger(action)}
              disabled={!action.isExecutable}
              aria-disabled={!action.isExecutable}
              title={!action.isExecutable ? `${action.label} is restricted` : action.label}
              className="rounded-sm outline-none hover:text-white focus-visible:ring-1 focus-visible:ring-white/50 transition-colors disabled:opacity-30 disabled:pointer-events-none cursor-pointer"
            >
              {action.label}
            </button>

            {index < actions.length - 1 && (
              <span className="text-white/30 pointer-events-none" aria-hidden="true">
                &middot;
              </span>
            )}
          </React.Fragment>
        ))}
      </div>
    </nav>
  );
});

export default SystemAction;
