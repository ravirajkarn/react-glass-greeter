import React, { useMemo, useCallback } from "react";
import { useNavigate } from "react-router";
import { PiLockKeyThin } from "react-icons/pi";

type PowerActionType = "hibernate" | "restart" | "shutdown";

interface PowerManager {
  isSupported: (action: PowerActionType) => boolean;
  execute: (action: PowerActionType) => void;
}

function useSystemPower(): PowerManager {
  const ldm = typeof window !== "undefined" ? (window as any).lightdm : undefined;

  const isSupported = useCallback(
    (action: PowerActionType): boolean => {
      switch (action) {
        case "hibernate":
          return ldm?.can_hibernate ?? true;
        case "restart":
          return ldm?.can_restart ?? true;
        case "shutdown":
          return ldm?.can_shutdown ?? true;
        default:
          return false;
      }
    },
    [ldm],
  );

  const execute = useCallback(
    (action: PowerActionType): void => {
      if (!isSupported(action)) {
        console.warn(`[SystemPower] ${action} is disabled by system policy.`);
        return;
      }

      if (ldm) {
        if (action === "hibernate") ldm.hibernate();
        if (action === "restart") ldm.restart();
        if (action === "shutdown") ldm.shutdown();
      } else {
        console.info(`[Dev Environment] Executed mock power action: ${action}`);
      }
    },
    [ldm, isSupported],
  );

  return { isSupported, execute };
}

interface SystemActionProps {
  className?: string;
  onActionTriggered?: (action: string) => void;
}

interface ActionConfig {
  id: PowerActionType | "switch_user";
  label: string;
  isExecutable: boolean;
  onTrigger: () => void;
}

const SystemAction = React.memo(function SystemAction({
  className = "",
  onActionTriggered,
}: SystemActionProps) {
  const navigate = useNavigate();
  const powerManager = useSystemPower();

  const actions: ActionConfig[] = useMemo(
    () => [
      {
        id: "switch_user",
        label: "Switch user",
        isExecutable: true,
        onTrigger: () => navigate("/lockScreen"),
      },
      {
        id: "restart",
        label: "Restart",
        isExecutable: powerManager.isSupported("restart"),
        onTrigger: () => powerManager.execute("restart"),
      },
      {
        id: "shutdown",
        label: "Shut down",
        isExecutable: powerManager.isSupported("shutdown"),
        onTrigger: () => powerManager.execute("shutdown"),
      },
    ],
    [powerManager, navigate],
  );

  const handleTrigger = useCallback(
    (action: ActionConfig) => {
      action.onTrigger();
      onActionTriggered?.(action.id);
    },
    [onActionTriggered],
  );

  return (
    <nav
      aria-label="System Power Controls"
      className={`inline-flex items-center gap-2.5 text-[13px] font-normal tracking-wide text-white/60 select-none ${className}`}
    >
      <button
        type="button"
        onClick={() => handleTrigger(actions[0])}
        aria-label="Lock screen"
        className="flex items-center justify-center p-0.5 -ml-0.5 rounded-sm hover:text-white hover:bg-white/10 outline-none focus-visible:ring-1 focus-visible:ring-white/50 transition-colors cursor-pointer"
      >
        <PiLockKeyThin className="text-[17px]" aria-hidden="true" />
      </button>

      <div className="flex items-center gap-2" role="group">
        {actions.map((action, index) => (
          <React.Fragment key={action.id}>
            <button
              type="button"
              onClick={() => handleTrigger(action)}
              disabled={!action.isExecutable}
              aria-disabled={!action.isExecutable}
              title={!action.isExecutable ? `${action.label} is restricted` : action.label}
              className="rounded-sm outline-none hover:text-white focus-visible:ring-1 focus-visible:ring-white/50 transition-colors disabled:opacity-30 disabled:pointer-events-none cursor-pointer"
            >
              {action.label}
            </button>

            {index < actions.length - 1 && (
              <span className="text-white/30 pointer-events-none" aria-hidden="true">
                &middot;
              </span>
            )}
          </React.Fragment>
        ))}
      </div>
    </nav>
  );
});

export default SystemAction;
